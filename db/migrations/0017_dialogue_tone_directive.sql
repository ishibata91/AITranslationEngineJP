-- C#↔Go 契約の SQL schema 正本（repo-owned migration）の 17 本目。
-- 本 migration は台詞の口調指示（directive の key 口調）を、実験 task dialogue-tone-naturalness が
-- 確定した文面へ更新する。テーブルは足さない。既存の 1 行の instruction だけを書き換える。
--
-- 0006 の seed は INSERT OR IGNORE なので、既に directive を持つ DB には新しい文面が入らない。
-- 配布前であり、人間が画面で独自に編集した内容を守る必要が無いため、条件を付けずに UPDATE する。
--
-- 文面を変えた理由を 3 つ書く。いずれも開発用 598 件と評価用 598 件で測った結果に基づく。
--   1. 主語を書かないことを明示した。英語の I と you をそのまま日本語の主語へ写す訳文が多く、
--      一人称を書く割合が 43.1% だった（同じ行の公式日本語既訳は 15.6%）。
--   2. 常体で書くことを、話者の属性に関わらず適用すると明示した。敬体を含む割合が 35.6% だった
--      （公式既訳は 6.9%）。丁寧な人物像の指示が敬体を呼んでいた。
--   3. 句点と全角空白の扱いを定めた。公式既訳は台詞の文末に句点を打たず、文の区切りに全角空白を使う。
-- 測定の記録は docs/exec-plans/active/dialogue-tone-naturalness/loop-log.md が持つ。

UPDATE directive SET instruction = 'この台詞の話者の人物像:
{traits}
この人物像に合う口調と人称で訳すこと。
台詞は話し手と聞き手が決まっているので、主語を書かなくても誰の話かは伝わる。英語の I と you を日本語の主語へ置き換えず、原則として書かない。
台詞は常体で書く。話者が女性でも年配でも礼儀正しくても、です・ます体にしない。
原文の内容をすべて訳す。そのうえで英語の語順と品詞をなぞらず、説明を足さずに短く言い切る。
台詞は文末に句点を打たない。原文が疑問符・感嘆符で終わる時だけ ？ ！ を置く。
1 つの台詞に文が 2 つ以上ある時は、句点でつなげず全角空白で区切る。'
WHERE key = '口調';
